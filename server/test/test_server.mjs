// End-to-end test of the local server (wrangler dev on 8787).
const B = process.argv[2] || 'http://127.0.0.1:8787';
const H = { 'content-type': 'application/json', Origin: 'http://localhost:8770' };
const call = async (method, path, tok, body) => {
  const r = await fetch(B + path, { method, headers: { ...H, ...(tok ? { Authorization: 'Bearer ' + tok } : {}) }, body: body ? JSON.stringify(body) : undefined });
  const t = await r.text();
  let j; try { j = JSON.parse(t); } catch (e) { j = t; }
  return { s: r.status, j, cors: r.headers.get('access-control-allow-origin') };
};
const ok = (cond, msg) => { console.log((cond ? 'OK  ' : 'FAIL') + ' ' + msg); if (!cond) process.exitCode = 1; };

const a = await call('POST', '/v1/users', null, { name: 'Haner <b>' });
const b = await call('POST', '/v1/users', null, { name: 'Ana' });
ok(a.s === 201 && /^[A-Z0-9]{24}$/.test(a.j.token) && /^[A-Z0-9]{6}$/.test(a.j.code), `create user (${a.j.name}, code ${a.j.code})`);
ok(a.j.name === 'Haner b', 'name cleaned');
ok(a.cors === 'http://localhost:8770', 'CORS for the app');
const A = a.j.token, Bt = b.j.token;
ok((await call('GET', '/v1/me', 'X'.repeat(24))).s === 401, 'bad token rejected');
ok((await call('GET', '/v1/me', A)).j.code === a.j.code, 'me');
ok((await call('PATCH', '/v1/me', A, { name: 'Haner' })).j.name === 'Haner', 'rename');
const f = await call('POST', '/v1/friends', A, { code: b.j.code.toLowerCase() });
ok(f.s === 201 && f.j.friend.name === 'Ana', 'add friend by code');
ok((await call('POST', '/v1/friends', A, { code: a.j.code })).s === 400, 'cannot add yourself');
ok((await call('GET', '/v1/friends', Bt)).j.friends.length === 1, 'friendship both ways');
ok((await call('POST', '/v1/scores', A, { c: 'pu60', n: 999 })).s === 400, 'impossible score rejected');
ok((await call('POST', '/v1/scores', A, { c: 'nope', n: 5 })).s === 400, 'unknown challenge rejected');
await call('POST', '/v1/scores', A, { c: 'pu60', n: 35 });
await call('POST', '/v1/scores', A, { c: 'pu60', n: 20 });
const r1 = await call('POST', '/v1/scores', Bt, { c: 'pu60', n: 41 });
ok(r1.j.list[0].name === 'Ana' && r1.j.list[0].n === 41 && r1.j.mine.pos === 1, 'ranking order');
const r2 = await call('GET', '/v1/rank/pu60', A);
ok(r2.j.list[1].n === 35 && r2.j.mine.pos === 2 && r2.j.list[1].me, 'best score kept (35, not 20), my position 2');
const c = await call('POST', '/v1/users', null, { name: 'Lejano' });
await call('POST', '/v1/scores', c.j.token, { c: 'pu60', n: 50 });
const g = await call('GET', '/v1/rank/pu60', A), fr = await call('GET', '/v1/rank/pu60?scope=friends', A);
ok(g.j.total === 3 && fr.j.total === 2 && fr.j.list.every((x) => x.name !== 'Lejano'), 'friends ranking only has friends');
const bk = await call('PUT', '/v1/backup', A, { v: 1, profile: { name: 'Haner' }, workouts: [1, 2, 3] });
ok(bk.s === 200, 'backup saved');
ok((await call('GET', '/v1/backup', A)).j.data.workouts.length === 3, 'backup restored');
ok((await call('GET', '/v1/backup', Bt)).s === 404, 'no backup for someone else');

// Live room: Haner creates, Ana joins, both ready -> go, counts, done.
const room = await call('POST', '/v1/rooms', A, { c: 'sq60', w: 0 });
ok(room.s === 201 && /^[A-Z0-9]{6}$/.test(room.j.code), 'room created ' + room.j.code);
const wsUrl = (tok) => B.replace('http', 'ws') + `/v1/rooms/${room.j.code}/ws?t=${tok}`;
const open = (tok) => new Promise((res, rej) => { const ws = new WebSocket(wsUrl(tok)); const log = []; ws.onmessage = (e) => log.push(JSON.parse(e.data)); ws.onopen = () => res({ ws, log }); ws.onerror = rej; });
const h = await open(A), an = await open(Bt);
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
await wait(400);
const st = (x) => [...x.log].reverse().find((m) => m.t === 'state');
ok(st(h).players.length === 2 && st(h).players.find((p) => p.host).name === 'Haner', 'both in the room, Haner is host');
h.ws.send(JSON.stringify({ t: 'ready', v: true }));
an.ws.send(JSON.stringify({ t: 'ready', v: true }));
await wait(400);
ok(an.log.some((m) => m.t === 'go'), 'everyone ready -> go');
an.ws.send(JSON.stringify({ t: 'n', n: 7 }));
await wait(300);
ok(st(h).players.find((p) => p.name === 'Ana').n === 7, 'Haner sees Ana count live');
const you = an.log.find((m) => m.t === 'you');
h.ws.send(JSON.stringify({ t: 'rtc', to: you.pid, data: { sdp: 'x' } }));
await wait(300);
ok(an.log.some((m) => m.t === 'rtc' && m.data.sdp === 'x'), 'camera connection message relayed');
h.ws.send(JSON.stringify({ t: 'done', n: 9 }));
an.ws.send(JSON.stringify({ t: 'done', n: 7 }));
await wait(400);
ok(st(h).phase === 'done', 'round done when everyone finished');
an.ws.close();
await wait(400);
ok(st(h).players.length === 1, 'leaving updates the room');
h.ws.close();
const bad = await new Promise((res) => { const ws = new WebSocket(B.replace('http', 'ws') + `/v1/rooms/${room.j.code}/ws?t=BAD`); ws.onerror = () => res('rejected'); ws.onopen = () => res('opened'); });
ok(bad === 'rejected', 'room needs a valid account');
// Activity and weekly league.
ok((await call('POST', '/v1/events', A, { kind: 'hack', data: {} })).s === 400, 'unknown activity rejected');
await call('POST', '/v1/events', A, { kind: 'workout', data: { w: 'Torso A <x>', sets: 18, evil: 'drop me' } });
await call('POST', '/v1/events', Bt, { kind: 'record', data: { c: 'pu60', n: 41 } });
await call('POST', '/v1/events', c.j.token, { kind: 'level', data: { n: 9 } });
const feed = await call('GET', '/v1/feed', A);
ok(feed.j.feed.length === 2 && !feed.j.feed.some((e) => e.name === 'Lejano'), 'feed has me and friends, not strangers');
ok(feed.j.feed.find((e) => e.kind === 'workout').data.evil === undefined && feed.j.feed.find((e) => e.kind === 'workout').data.w === 'Torso A x', 'activity data cleaned');
const anaEv = feed.j.feed.find((e) => e.name === 'Ana');
ok((await call('POST', `/v1/events/${anaEv.id}/cheer`, A)).j.cheers === 1, 'cheer a friend');
ok((await call('POST', `/v1/events/${anaEv.id}/cheer`, A)).j.cheers === 1, 'cheer counts once per person');
const strangerEv = (await call('GET', '/v1/feed', c.j.token)).j.feed[0];
ok((await call('POST', `/v1/events/${strangerEv.id}/cheer`, A)).s === 403, 'cannot cheer a stranger');
await call('PUT', '/v1/xp', A, { xp: 120 });
await call('PUT', '/v1/xp', Bt, { xp: 340 });
await call('PUT', '/v1/xp', c.j.token, { xp: 999 });
await call('PUT', '/v1/xp', A, { xp: 80 });
ok((await call('PUT', '/v1/xp', A, { xp: 999999 })).s === 400, 'impossible XP rejected');
const lg = await call('GET', '/v1/league', A);
ok(lg.j.league.length === 2 && lg.j.league[0].name === 'Ana' && lg.j.league[1].xp === 120 && lg.j.league[1].me, 'league: friends only, sorted, XP never goes down');
const ai = await call('POST', '/v1/coach', A, { lang: 'es', messages: [{ me: true, text: '¿agua con sal antes de entrenar?' }] });
console.log('coach (local has no AI, 503 expected):', ai.s, JSON.stringify(ai.j).slice(0, 100));
